LIST p=16f887
#include <p16f887.inc>

	__CONFIG _WDT_OFF & _XT_OSC
	ORG 0X00
	GOTO setup

	ORG 0X05
setup:
	BANKSEL	TRISD
	CLRF	TRISD
	CLRF	TRISC

	BANKSEL	PORTD
	MOVLW	0XFF
	MOVWF	PORTD
	MOVLW	b'00010001'
	MOVWF	PORTC

main:	MOVLW	.62
	MOVWF	0X20
loop3:	MOVLW	.58
	MOVWF	0X21
loop2:	MOVLW	.91
	MOVWF	0X22

loop1:	DECFSZ	0X22
	GOTO	loop1
	DECFSZ	0X21
	GOTO	loop2	
	DECFSZ	0X20
	GOTO	loop3	

	RLF	PORTC, F

	GOTO	main
	END
